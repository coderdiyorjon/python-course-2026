"""Demonstrate ordinary comments and a module docstring."""

# A full-line comment explains the purpose of the next line.
print("Welcome to Python!")

course_name = "Python Fundamentals"  # Short inline comment.
print("Course:", course_name)

# A group of comment lines can explain a larger idea.
# Each line still begins with #; Python has no separate
# special syntax for a general multi-line comment block.
print("Comments make code easier to understand when used well.")

# A hash sign inside a string is just a character, not a comment.
print("This is a hashtag: #python")

# Avoid comments that merely repeat what a simple line does:
# print a greeting
print("Hello!")
